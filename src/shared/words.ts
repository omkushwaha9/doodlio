export function getWordsForCategory(category: WordCategory): string[] {
  if (category === 'All') {
    const unique = new Set<string>();
    for (const list of Object.values(CATEGORIZED_WORDS)) {
      for (const word of list) {
        unique.add(word);
      }
    }
    return Array.from(unique);
  }
  return Array.from(new Set(CATEGORIZED_WORDS[category] ?? []));
}
